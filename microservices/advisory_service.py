@app.post("/api/v1/advisory/generate", response_model=AdvisoryResponse, tags=["Advisory"])
def generate_advisory(req: AdvisoryRequest):
    """
    Decoupled Microservice API Endpoint:
    Processes raw meteorological variables through NOAA Rothfusz regression
    and outputs categorized, stakeholder-tailored advisories with multilingual support.
    """
    start_time = time.perf_counter()

    try:
        # 1. Calculate temperature anomaly against baseline
        anomaly = wa.calculate_temperature_anomaly(req.temperature, req.baseline_temp)

        # 2. Categorize risk level (Normal, Mild Heat, Severe Heat, Extreme Alert)
        risk = wa.classify_heatwave_risk(req.temperature, anomaly)

        # 3. Calculate physiological Heat Index (NOAA Rothfusz regression in °C)
        heat_idx = wa.calculate_heat_index(req.temperature, req.relative_humidity)

        # 4. Generate core stakeholder guidance
        core_advisory = wa.generate_stakeholder_advisory(
            region=req.region,
            risk_level=risk["status"],
            category=req.stakeholder_type.value
        )
    except (ValueError, TypeError) as e:
        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
            detail=f"Mathematical processing error: {str(e)}"
        )

    # 5. Extract structured action items and apply language translations
    action_items = [core_advisory]
    if risk["level"] >= 3:
        action_items.append(f"Deploy emergency cooling hubs and prioritize heat stroke prevention in {req.region}.")
        action_items.append(f"Enforce mandatory rest and hydration intervals for {req.stakeholder_type.value} personnel.")
    else:
        action_items.append(f"Continue monitoring localized Automated Weather Station (AWS) telemetry in {req.region}.")

    lang = req.language.value
    trans = TRANSLATIONS.get(lang, TRANSLATIONS["en"])
    risk_title = trans.get(risk["status"], risk["status"])

    headline = f"[{trans['action_prefix']}{risk_title}] Region: {req.region} | Heat Index: {heat_idx}°C"

    duration_ms = round((time.perf_counter() - start_time) * 1000, 2)

    return AdvisoryResponse(
        timestamp=time.time(),
        execution_time_ms=duration_ms,
        region=req.region,
        stakeholder_type=req.stakeholder_type.value,
        language=lang,
        metrics=HeatMetrics(
            temperature_celsius=req.temperature,
            baseline_celsius=req.baseline_temp,
            anomaly_celsius=anomaly,
            heat_index_celsius=heat_idx,
            risk_status=risk["status"],
            risk_level=risk["level"],
            badge_class=risk["badge_class"]
        ),
        advisory_headline=headline,
        action_items=action_items,
        disclaimer=trans["disclaimer"]
    )


